    document.addEventListener('DOMContentLoaded', function () {
        const faqItems = document.querySelectorAll('.faq-item');
        faqItems.forEach(function (item, index) {
            const btn = item.querySelector('.faq-question-btn');
            const answer = item.querySelector('.faq-answer-wrap');
            const chevron = item.querySelector('.faq-chevron');

            if (index === 0) {
                answer.style.display = 'block';
                item.style.borderColor = '#93c5fd';
                item.style.boxShadow = '0 4px 14px rgba(37,99,235,0.08)';
                if (chevron) chevron.style.transform = 'rotate(180deg)';
            }

            btn.addEventListener('click', function () {
                const isOpen = (answer.style.display === 'block');
                faqItems.forEach(function (other) {
                    other.querySelector('.faq-answer-wrap').style.display = 'none';
                    other.style.borderColor = '#e2e8f0';
                    other.style.boxShadow = '0 2px 8px rgba(0,0,0,0.02)';
                    const otherChevron = other.querySelector('.faq-chevron');
                    if (otherChevron) otherChevron.style.transform = 'rotate(0deg)';
                });

                if (!isOpen) {
                    answer.style.display = 'block';
                    item.style.borderColor = '#93c5fd';
                    item.style.boxShadow = '0 4px 14px rgba(37,99,235,0.08)';
                    if (chevron) chevron.style.transform = 'rotate(180deg)';
                }
            });
        });

        if (window.location.hash === '#faq') {
            const faqSection = document.getElementById('faq');
            if (faqSection) {
                setTimeout(function() {
                    faqSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }, 150);
            }
        } else if (window.location.hash === '#huong-dan') {
            const guideSection = document.getElementById('huong-dan');
            if (guideSection) {
                setTimeout(function() {
                    guideSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }, 150);
            }
        }
    });
